def art(s):
    return [r for r in s.strip('\n').split('\n')]


def cols8(rows, width=None, margin=0):
    """rows (top->bottom, <=8) -> list of column bytes, bit7 = top row."""
    w = max(len(r) for r in rows)
    out = []
    for c in range(w):
        b = 0
        for r, row in enumerate(rows):
            if c < len(row) and row[c] == '#':
                b |= 0x80 >> r
        out.append(b)
    out = [0] * margin + out + [0] * margin
    if width:
        out += [0] * (width - len(out))
    return out


def cols16(rows):
    """16-row art -> per column (low byte = bottom 8 rows, high byte = top 8 rows)."""
    w = len(rows[0])
    out = []
    for c in range(w):
        v = 0
        for r, row in enumerate(rows):
            if row[c] == '#':
                v |= 1 << (15 - r)
        out += [v & 0xFF, v >> 8]
    return out


def glyph(ch):
    rows = FONT5x7[ch].split()
    out = [0]
    for c in range(5):
        b = 0
        for r, row in enumerate(rows):
            if row[c] == '1':
                b |= 0x80 >> r
        out.append(b)
    return out + [0, 0]


