def glyph7(ch):
    rows = art(FONT7[ch])
    assert len(rows) == 7 and all(len(r) == 7 for r in rows), ch
    return cols8(rows, 8)

def db(label, data, per=16):
    lines = [f'{label}:'] if label else []
    for i in range(0, len(data), per):
        lines.append('        DB   ' + ', '.join(f'0{b:02X}H' for b in data[i:i + per]))
    return '\n'.join(lines)


def main():
    out = ['; Generated by tools/gen_gfx.py - do not edit', '']
    font = []
    for code in range(0x20, 0x60):
        ch = chr(code)
        font += glyph7(ch) if ch in FONT7 else glyph(ch) if ch in FONT5x7 else [0] * 8
    out.append(db('FONT', font))   # ASCII 20h-5Fh, 8 bytes each
    for name, frames in (('A', ALIEN_A), ('B', ALIEN_B), ('C', ALIEN_C)):
        for i, f in enumerate(frames):
            out.append(db(f'SPR_{name}{i}', cols8(art(f), 16, 2)))
    out.append(db('SPR_PLAYER', cols8(art(PLAYER), 16, 1)))
    out.append(db('SPR_PX0', cols8(art(PLAYER_X0), 16, 1)))
    out.append(db('SPR_PX1', cols8(art(PLAYER_X1), 16, 1)))
    out.append(db('SPR_EXPL', cols8(art(EXPL), 16, 2)))
    out.append(db('SPR_UFO', cols8(art(UFO), 20, 2)))
    out.append(db('SPR_SHIELD', cols16(art(SHIELD))))
    path = os.path.join(os.path.dirname(__file__), 'gfx.inc')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
