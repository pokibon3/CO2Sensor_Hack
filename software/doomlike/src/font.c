static const uint8_t *find(char c)
{
  for(unsigned i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
  {
    if(glyphs[i].c == c)
    {
      return glyphs[i].rows;
    }
  }
  return 0;
}

int text_width(const char *s, int scale)
{
  int n = 0;
  while(s[n] != '\0')
  {
    n++;
  }
  return n == 0 ? 0 : (n * 6 - 1) * scale;
}

void text_draw(int x, int y, const char *s, int scale, uint16_t color)
{
  for(; *s != '\0'; s++, x += 6 * scale)
  {
    const uint8_t *rows = find(*s);
    if(rows == 0)
    {
      continue;
    }
    for(int r = 0; r < 7; r++)
    {
      /* one rectangle per horizontal run of set pixels */
      int c = 0;
      while(c < 5)
      {
        if((rows[r] & (0x10u >> c)) == 0u)
        {
          c++;
          continue;
        }
        int start = c;
        while(c < 5 && (rows[r] & (0x10u >> c)) != 0u)
        {
          c++;
        }
        gfx_fill(x + start * scale, y + r * scale, (c - start) * scale, scale, color);
      }
    }
  }
}

void text_center(int y, const char *s, int scale, uint16_t color)
{
  text_draw((SCREEN_W - text_width(s, scale)) / 2, y, s, scale, color);
}
